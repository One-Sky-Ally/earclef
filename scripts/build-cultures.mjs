/**
 * Build lib/explore/cultures.json — the Explore page's curated journeys
 * and "Music cultures" row (see scripts/lib/cultures.mjs for the rules).
 * Reads committed files only, no network, so it runs before every build
 * (package.json "build") and the page can never drift from its sources:
 *   node scripts/build-cultures.mjs
 *
 * The On-this-day shards (8.6 MB) are read here, at build time; the page
 * ships only journey summaries, and each journey's songs load on demand
 * from /api/explore/journey/[id].
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import {
  buildDecadeJourneys,
  buildEraJourneys,
  buildSongPlaces,
  verifiedIndex,
} from './lib/cultures.mjs'

const ROOT = process.cwd()
const read = (path) => JSON.parse(readFileSync(join(ROOT, path), 'utf8'))
const OUT_PATH = join(ROOT, 'lib', 'explore', 'cultures.json')

const playing = read('lib/explore/playing.json').entries
const hitsPlay = read('lib/hits/hits-play.json')
const songPlaces = read('lib/explore/songs-about-places.json').places
// Children's and educational families never lead a place (owner ruling,
// Aug 2026) — and a curated journey is a lead.
const demotedTags = new Set(
  read('lib/explore/genre-families.json')
    .families.filter((family) => family.demote)
    .flatMap((family) => [family.label, ...family.tags])
    .map((tag) => tag.toLowerCase()),
)

const otdItems = []
for (let month = 1; month <= 12; month++) {
  const shard = read(`lib/explore/on-this-day/${String(month).padStart(2, '0')}.json`)
  for (const day of Object.values(shard.days)) otdItems.push(...(day.items ?? []))
}

const regionNames = new Intl.DisplayNames(['en'], { type: 'region' })
const countryName = (code) => regionNames.of(code) ?? code

const index = verifiedIndex({ hitsPlay, songPlaces, otdItems })
const eras = buildEraJourneys(playing, index, countryName, demotedTags)
const decades = buildDecadeJourneys(index, countryName, eras, demotedTags)
const songs = buildSongPlaces(songPlaces)

const output = {
  // Deterministic: no timestamp, so an unchanged input rebuilds to an
  // identical file and a build never dirties the tree.
  note: 'Generated by scripts/build-cultures.mjs from playing.json, hits-play.json, songs-about-places.json and the on-this-day shards. Do not edit by hand.',
  eras,
  decades,
  songs,
}

writeFileSync(OUT_PATH, JSON.stringify(output) + '\n')
const dropped = playing.length - eras.length
console.log(
  `cultures: ${eras.length} era journeys (${dropped} left out, too few playable songs), ${decades.length} decade journeys across ${new Set(decades.map((d) => d.code)).size} countries, ${songs.length} song places -> lib/explore/cultures.json`,
)
